function lowResolutionMessage(widthPx: number, heightPx: number, dpi: number): string {
  const panel = baseArtworkFit(widthPx, heightPx) === 'PANEL';
  const min = panel ? MIN_PANEL_PNG : MIN_BASE_PNG;
  const rec = panel ? RECOMMENDED_PANEL_PNG : { widthPx: 2700, heightPx: 600 };
  return `PNG resolution too low: ${widthPx} × ${heightPx} px prints at ${dpi} DPI. Minimum ${min.widthPx} × ${min.heightPx} px (300 DPI); recommended ${rec.widthPx} × ${rec.heightPx} px (600 DPI). Low-resolution images are never upscaled.`;
}

/** SHA-256 of a studio document's canonical JSON (stable key order) for audit trails. */
export function studioSha(doc: unknown): string {
  const canon = (v: unknown): unknown =>
    Array.isArray(v)
      ? v.map(canon)
      : v && typeof v === 'object'
        ? Object.fromEntries(
            Object.keys(v as object)
              .sort()
              .map((k) => [k, canon((v as Record<string, unknown>)[k])]),
          )
        : v;
  return sha256(Buffer.from(JSON.stringify(canon(doc)), 'utf8'));
}

export function sha256(buf: Buffer): string {
  return createHash('sha256').update(buf).digest('hex');
}

/** Renders one real sample unit to an in-memory PDF (proves the artwork renders). */
async function renderSamplePdf(
  ctx: ReturnType<PrintService['context']>,
  print: PrintService,
): Promise<void> {
  const pdf = new SheetPdf({
    layout: DEFAULT_PRINT_LAYOUT,
    fonts: print.fonts,
    title: 'validation',
  });
  const done = new Promise<void>((resolve, reject) => {
    pdf.doc.on('error', reject);
    pdf.doc.pipe(
      new Writable({
        write(_c, _e, cb) {
          cb();
        },
        final(cb) {
          resolve();
          cb();
        },
      }),
    );
  });
  pdf.addUnit(0, layoutUnit(print.sampleUnit(true), ctx));
  pdf.end();
  await done;
}
