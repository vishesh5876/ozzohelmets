/** Loaded, hash-verified artwork for rendering. */
export interface RenderableDesign {
  id: string;
  name: string;
  version: number;
  position: ArtworkPosition;
  base: ArtworkAsset;
  cover: ArtworkAsset | null;
  sha256: { base: string; cover: string | null };
}

export interface UploadedFile {
  buffer: Buffer;
  originalname?: string;
  mimetype?: string;
}

/** `../../etc/passwd`, `C:\\x.svg`, control characters → a plain display name (metadata only). */
export function safeFilename(name: string | undefined): string {
  const base = (name ?? 'artwork').split(/[\\/]/).pop() ?? 'artwork';
  const clean = base
    // eslint-disable-next-line no-control-regex -- stripping control characters is the point
    .replace(/[\u0000-\u001f\u007f<>:"|?*]/g, '')
    .trim()
    .slice(0, 200);
  return clean && !/^\.+$/.test(clean) ? clean : 'artwork';
}

/**
 * Print Designs: admin-uploaded Safety ID artwork, versioned and immutable once used. The
 * artwork is only a background — ID, PIN, QR (+ quiet zone, white credential panel), cut and
 * cover geometry stay system-generated by the print engine.
 */
@Injectable()
export class PrintDesignsService {
  private readonly logger = new Logger(PrintDesignsService.name);

  constructor(
    private readonly prisma: PrismaService,
    private readonly audit: AuditService,
    private readonly config: AppConfigService,
    private readonly print: PrintService,
    @Inject(FILE_STORAGE_PROVIDER) private readonly storage: FileStorageProvider,
  ) {}

  // ── Artwork upload ──────────────────────────────────────────────────────────────────────────

  async uploadArtwork(
    file: UploadedFile | undefined,
    role: PrintArtworkRole,
    testOnly: boolean,
    admin: AuthenticatedAdmin,
    meta: RequestMeta,
  ): Promise<PrintArtworkFileDto> {
    if (!file?.buffer?.length) throw this.invalidArtwork('Choose an SVG or PNG file to upload.');
    if (testOnly && admin.role !== 'SUPER_ADMIN')
      throw this.invalidArtwork('Only a SUPER_ADMIN can allow test-only low-resolution artwork.');
    const input = file.buffer;
    const originalFilename = safeFilename(file.originalname);
    const ext = /\.([a-z0-9]+)$/i.exec(originalFilename)?.[1]?.toLowerCase();
    const sourceSha256 = sha256(input);
    let format: 'SVG' | 'PNG';
    if (isPng(input)) format = 'PNG';
    // Anything XML-like goes to the strict sanitizer, which gives the precise rejection reason.
    else if (
      /^\s*</.test(
        input
          .subarray(0, 1024)
          .toString('utf8')
          .replace(/^\uFEFF/, ''),
      )
    )
      format = 'SVG';
    else throw this.invalidArtwork('Unsupported file type: upload an SVG or a PNG.');
    // The content decides; the declared name/type must agree with it (no disguised files).
    const expectedExt = format === 'SVG' ? 'svg' : 'png';
    const expectedMime = format === 'SVG' ? 'image/svg+xml' : 'image/png';
    if (ext !== expectedExt || (file.mimetype && file.mimetype !== expectedMime))
      throw this.invalidArtwork(
        `Wrong file type: the content is ${format} but the file is named/sent as ${file.mimetype ?? ext ?? 'unknown'}.`,
      );

    let stored: Buffer;
    let facts: ArtworkFacts;
    let svgViewBox: string | null = null;
    try {
      if (format === 'SVG') {
        // The downloadable templates carry their guides in this layer; never print them.
        if (input.toString('utf8').includes(TEMPLATE_GUIDE_LAYER))
          throw new ArtworkError(
            `This file still contains the template guides. Delete the "${TEMPLATE_GUIDE_LAYER}" layer, then export again.`,
          );
        const clean = sanitizeSvg(
          input,
          {
            maxBytes: this.config.get('PRINT_ARTWORK_SVG_MAX_BYTES'),
            maxElements: this.config.get('PRINT_ARTWORK_SVG_MAX_ELEMENTS'),
          },
          `a${sourceSha256.slice(0, 10)}-`,
        );
        stored = Buffer.from(clean.svg, 'utf8');
        svgViewBox = clean.viewBoxText;
        facts = {
          format,
          widthPx: null,
          heightPx: null,
          viewBox: clean.viewBox,
          testOnly: false,
          warnings: clean.warnings,
        };
      } else {
        const info = await inspectPng(input, {
          maxBytes: this.config.get('PRINT_ARTWORK_PNG_MAX_BYTES'),
          maxPixels: this.config.get('PRINT_ARTWORK_PNG_MAX_PIXELS'),
        });
        try {
          (
            new PDFDocument({ autoFirstPage: false }) as unknown as {
              openImage(b: Buffer): unknown;
            }
          ).openImage(input);
        } catch {
          throw new ArtworkError('The PNG cannot be embedded in a PDF (unsupported PNG variant).');
        }
        stored = input; // original bytes: never re-encoded
        facts = {
          format,
          widthPx: info.widthPx,
          heightPx: info.heightPx,
          viewBox: null,
          testOnly,
          warnings: [],
        };
      }
    } catch (err) {
      if (err instanceof ArtworkError) throw this.invalidArtwork(err.message);
      throw err;
    }

    // Role-specific checks at upload (the design is re-validated authoritatively later).
    let effectiveDpi: number | null = null;
    if (role === 'base') {
      const [w, h] =
        format === 'SVG'
          ? [facts.viewBox!.width, facts.viewBox!.height]
          : [facts.widthPx!, facts.heightPx!];
      if (!baseArtworkFit(w, h)) throw this.invalidArtwork(baseArtworkAspectMessage(w / h));
    }
    if (format === 'PNG') {
      const box =
        role === 'base'
          ? placeBaseArtwork(facts.widthPx! / facts.heightPx!, {
              scalePercent: 100,
              offsetXMm: 0,
              offsetYMm: 0,
            })
          : placeCoverArtwork(
              facts.widthPx! / facts.heightPx!,
              this.print.geometry(DEFAULT_PRINT_LAYOUT).coverYellow,
            );
      effectiveDpi = drawnDpi(facts.widthPx!, facts.heightPx!, box);
      if (effectiveDpi < MIN_PRINT_DPI && !testOnly)
        throw this.invalidArtwork(
          role === 'base'
            ? lowResolutionMessage(facts.widthPx!, facts.heightPx!, effectiveDpi)
            : `PNG resolution too low for the cover: prints at ${effectiveDpi} DPI (minimum ${MIN_PRINT_DPI}).`,
        );
      if (effectiveDpi >= MIN_PRINT_DPI) facts.testOnly = false;
    }

    const digest = sha256(stored);
    const existing = await this.prisma.printArtworkFile.findUnique({ where: { sha256: digest } });
    if (existing) return { ...this.fileDto(existing), duplicate: true };

    const id = uuidv7();
    const storageKey = `print-designs/${randomUUID()}.${expectedExt}`;
    await this.storage.put(storageKey, stored, expectedMime);
    const row = await this.prisma.printArtworkFile.create({
      data: {
        id,
        storageKey,
        format,
        originalFilename,
        mimeType: expectedMime,
        sha256: digest,
        sourceSha256,
        sizeBytes: stored.length,
        widthPx: facts.widthPx,
        heightPx: facts.heightPx,
        svgViewBox,
        effectiveDpi: role === 'base' ? effectiveDpi : null,
        testOnly: facts.testOnly,
        warnings: facts.warnings,
        uploadedBy: admin.id,
      },
    });
    await this.audit.record({
      action: AuditAction.PRINT_ARTWORK_UPLOADED,
      entityType: 'print_artwork',
      entityId: row.id,
      adminId: admin.id,
      ipHash: meta.ipHash,
      metadata: {
        format,
        role,
        sha256: digest,
        sourceSha256,
        sizeBytes: stored.length,
        testOnly: row.testOnly,
      },
    });
    return this.fileDto(row);
  }

  // ── Designs ─────────────────────────────────────────────────────────────────────────────────

  async list(status?: string): Promise<PrintDesignDto[]> {
    const rows = await this.prisma.printDesign.findMany({
      where: status ? { status: status as DesignRow['status'] } : {},
      include,
      orderBy: [{ name: 'asc' }, { version: 'desc' }],
    });
    const usage = await this.usage(rows.map((r) => r.id));
    return rows.map((r) => this.toDto(r, usage.get(r.id) ?? 0));
  }

  async get(id: string): Promise<PrintDesignDto> {
    const row = await this.findRow(id);
    return this.toDto(row, (await this.usage([id])).get(id) ?? 0);
  }

  async active(): Promise<PrintDesignDto | null> {
    const row = await this.prisma.printDesign.findFirst({ where: { status: 'ACTIVE' }, include });
    return row ? this.toDto(row, (await this.usage([row.id])).get(row.id) ?? 0) : null;
  }

  async create(
    input: {
      name: string;
      baseArtworkFileId: string;
      coverArtworkFileId?: string | null;
    } & Partial<ArtworkPosition>,
    admin: AuthenticatedAdmin,
    meta: RequestMeta,
  ): Promise<PrintDesignDto> {
    const familyId = uuidv7();
    const row = await this.insertVersion(
      {
        familyId,
        version: 1,
        name: input.name,
        baseArtworkFileId: input.baseArtworkFileId,
        coverArtworkFileId: input.coverArtworkFileId ?? null,
        position: this.position(input),
      },
      admin,
    );
    await this.auditDesign(AuditAction.PRINT_DESIGN_CREATED, row, admin, meta);
    return this.get(row.id);
  }

  /** Edits a DRAFT that no batch uses. Anything else is immutable: create a new version. */
  async update(
    id: string,
    input: Partial<
      {
        name: string;
        baseArtworkFileId: string;
        coverArtworkFileId: string | null;
      } & ArtworkPosition
    >,
    admin: AuthenticatedAdmin,
    meta: RequestMeta,
  ): Promise<PrintDesignDto> {
    const row = await this.findRow(id);
    if (row.status !== 'DRAFT' || ((await this.usage([id])).get(id) ?? 0) > 0)
      throw new AppException(
        ErrorCode.PRINT_DESIGN_LOCKED,
        'This design version is locked (active, archived or used by a batch). Create a new version to change it.',
        HttpStatus.CONFLICT,
      );
    const base = input.baseArtworkFileId
      ? await this.fileRow(input.baseArtworkFileId)
      : row.baseArtwork;
    const coverId =
      input.coverArtworkFileId === undefined ? row.coverArtworkFileId : input.coverArtworkFileId;
    const cover = coverId ? await this.fileRow(coverId) : null;
    const position = this.position({
      scalePercent: input.scalePercent ?? row.scalePercent,
      offsetXMm: input.offsetXMm ?? row.offsetXMm,
      offsetYMm: input.offsetYMm ?? row.offsetYMm,
    });
    const check = this.check(base, cover, position);
    await this.prisma.printDesign.update({
      where: { id },
      data: {
        name: input.name?.trim() ?? row.name,
        baseArtworkFileId: base.id,
        coverArtworkFileId: cover?.id ?? null,
        artworkType: base.format,
        ...position,
        validationErrors: check.errors,
        validationWarnings: check.warnings,
      },
    });
    const updated = await this.findRow(id);
    await this.auditDesign(AuditAction.PRINT_DESIGN_UPDATED, updated, admin, meta);
    return this.get(id);
  }

  /** New DRAFT version in the same family (the source version is never modified). */
  async newVersion(
    id: string,
    input: Partial<
      {
        name: string;
        baseArtworkFileId: string;
        coverArtworkFileId: string | null;
      } & ArtworkPosition
    >,
    admin: AuthenticatedAdmin,
    meta: RequestMeta,
  ): Promise<PrintDesignDto> {
    const src = await this.findRow(id);
    const row = await this.prisma.$transaction(async (tx) => {
      // Serialise version numbering per family.
      await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtext(${src.familyId}))`;
      const max = await tx.printDesign.aggregate({
        where: { familyId: src.familyId },
        _max: { version: true },
      });
      return this.insertVersion(
        {
          familyId: src.familyId,
          version: (max._max.version ?? 0) + 1,
          name: input.name ?? src.name,
          baseArtworkFileId: input.baseArtworkFileId ?? src.baseArtworkFileId,
          coverArtworkFileId:
            input.coverArtworkFileId === undefined
              ? src.coverArtworkFileId
              : input.coverArtworkFileId,
          position: this.position({
            scalePercent: input.scalePercent ?? src.scalePercent,
            offsetXMm: input.offsetXMm ?? src.offsetXMm,
            offsetYMm: input.offsetYMm ?? src.offsetYMm,
          }),
        },
        admin,
        tx,
      );
    });
    await this.auditDesign(AuditAction.PRINT_DESIGN_VERSION_CREATED, row, admin, meta, {
      fromDesignId: src.id,
      fromVersion: src.version,
    });
    return this.get(row.id);
  }

  /** A new design family (v1 DRAFT) starting from this version's artwork and position. */
  async duplicate(
    id: string,
    admin: AuthenticatedAdmin,
    meta: RequestMeta,
  ): Promise<PrintDesignDto> {
    const src = await this.findRow(id);
    const row = await this.insertVersion(
      {
        familyId: uuidv7(),
        version: 1,
        name: `${src.name} (copy)`.slice(0, 120),
        baseArtworkFileId: src.baseArtworkFileId,
        coverArtworkFileId: src.coverArtworkFileId,
        position: {
          scalePercent: src.scalePercent,
          offsetXMm: src.offsetXMm,
          offsetYMm: src.offsetYMm,
        },
      },
      admin,
    );
    await this.auditDesign(AuditAction.PRINT_DESIGN_DUPLICATED, row, admin, meta, {
      fromDesignId: src.id,
      fromVersion: src.version,
    });
    return this.get(row.id);
  }

  /**
   * Full validation (files present + hash, rules, sample render) then: this design ACTIVE, the
   * previous ACTIVE one ARCHIVED. Existing batches are untouched (they reference their version).
   */
  async activate(
    id: string,
    admin: AuthenticatedAdmin,
    meta: RequestMeta,
  ): Promise<PrintDesignDto> {
    const row = await this.findRow(id);
    const errors = await this.fullValidation(row);
    if (errors.length)
      throw new AppException(
        ErrorCode.PRINT_DESIGN_INVALID,
        `This design cannot be activated: ${errors.join(' ')}`,
        HttpStatus.CONFLICT,
        { errors },
      );
    const previous = await this.prisma.$transaction(async (tx) => {
      const prev = await tx.printDesign.findFirst({
        where: { status: 'ACTIVE', id: { not: id } },
        select: { id: true, version: true, name: true },
      });
      const now = new Date();
      if (prev)
        await tx.printDesign.update({
          where: { id: prev.id },
          data: { status: 'ARCHIVED', archivedAt: now },
        });
      await tx.printDesign.update({
        where: { id },
        data: { status: 'ACTIVE', activatedAt: now, archivedAt: null },
      });
      return prev;
    });
    await this.auditDesign(AuditAction.PRINT_DESIGN_ACTIVATED, row, admin, meta, {
      previousActiveDesignId: previous?.id ?? null,
      previousActiveVersion: previous?.version ?? null,
    });
    return this.get(id);
  }

  async archive(id: string, admin: AuthenticatedAdmin, meta: RequestMeta): Promise<PrintDesignDto> {
    const row = await this.findRow(id);
    if (row.status === 'ARCHIVED') return this.get(id);
    await this.prisma.printDesign.update({
      where: { id },
      data: { status: 'ARCHIVED', archivedAt: new Date() },
    });
    await this.auditDesign(AuditAction.PRINT_DESIGN_ARCHIVED, row, admin, meta, {
      wasActive: row.status === 'ACTIVE',
    });
    return this.get(id);
  }

  /** Only an unused DRAFT can be deleted (designs referenced by batches are kept forever). */
  async remove(id: string, admin: AuthenticatedAdmin, meta: RequestMeta): Promise<void> {
    const row = await this.findRow(id);
    if (row.status !== 'DRAFT' || ((await this.usage([id])).get(id) ?? 0) > 0)
      throw new AppException(
        ErrorCode.PRINT_DESIGN_LOCKED,
        'Only an unused draft can be deleted. Archive designs that were active or used by a batch.',
        HttpStatus.CONFLICT,
      );
    await this.prisma.printDesign.delete({ where: { id } });
    await this.auditDesign(AuditAction.PRINT_DESIGN_DELETED, row, admin, meta);
  }

  // ── Batch binding ───────────────────────────────────────────────────────────────────────────

  /**
   * The design version a NEW batch binds to: the requested one (not archived, valid, renders) or
   * the ACTIVE default. Null = no design yet (the batch uses the built-in legacy layout).
   */
  async resolveForNewBatch(
    printDesignId: string | undefined,
  ): Promise<{ id: string; version: number } | null> {
    if (!printDesignId) {
      const active = await this.prisma.printDesign.findFirst({
        where: { status: 'ACTIVE' },
        select: { id: true, version: true },
      });
      return active;
    }
    const row = await this.findRow(printDesignId);
    if (row.status === 'ARCHIVED')
      throw new AppException(
        ErrorCode.PRINT_DESIGN_INVALID,
        'Archived print designs cannot be used for new batches.',
        HttpStatus.CONFLICT,
      );
    if (row.status !== 'ACTIVE') {
      const errors = await this.fullValidation(row);
      if (errors.length)
        throw new AppException(
          ErrorCode.PRINT_DESIGN_INVALID,
          `This print design is not ready for production: ${errors.join(' ')}`,
          HttpStatus.CONFLICT,
          { errors },
        );
    }
    return { id: row.id, version: row.version };
  }

  /**
   * The exact artwork a batch was created with, verified byte-for-byte (SHA-256). Never falls
   * back to another design: a missing or altered file is a hard failure.
   */
  async loadRenderable(id: string): Promise<RenderableDesign> {
    const row = await this.prisma.printDesign.findUnique({ where: { id }, include });
    if (!row) throw this.unavailable();
    const base = await this.loadAsset(row.baseArtwork);
    const cover = row.coverArtwork ? await this.loadAsset(row.coverArtwork) : null;
    return {
      id: row.id,
      name: row.name,
      version: row.version,
      position: {
        scalePercent: row.scalePercent,
        offsetXMm: row.offsetXMm,
        offsetYMm: row.offsetYMm,
      },
      base,
      cover,
      sha256: { base: row.baseArtwork.sha256, cover: row.coverArtwork?.sha256 ?? null },
    };
  }

  contextOptions(d: RenderableDesign, extra: ContextOptions = {}): ContextOptions {
    return { ...extra, artwork: { base: d.base, cover: d.cover, position: d.position } };
  }

  // ── Previews and test print (sample data only) ──────────────────────────────────────────────

  async previewSvg(
    id: string,
    kind: 'unit' | 'sheet',
    layout: PrintSheetLayout,
    opts: { guides?: boolean; position?: Partial<ArtworkPosition>; filled?: number },
  ): Promise<string> {
    const d = await this.loadRenderable(id).catch((err) => {
      if (err instanceof AppException) throw err;
      throw this.unavailable();
    });
    const position = this.position({ ...d.position, ...opts.position });
    const ctx = this.contextOptions({ ...d, position }, { guides: opts.guides });
    return kind === 'unit'
      ? this.print.previewUnitSvg(layout, ctx)
      : this.print.previewSheetSvg(layout, opts.filled ?? unitsPerSheet(layout), ctx);
  }

  /** One production-size sheet of sample units, every unit marked TEST PRINT. Never a real PIN. */
  async streamTestPrint(
    id: string,
    layout: PrintSheetLayout,
    admin: AuthenticatedAdmin,
    meta: RequestMeta,
    res: Response,
  ): Promise<void> {
    const d = await this.loadRenderable(id);
    const ctx = this.print.context(layout, this.contextOptions(d, { testPrint: true }));
    const unit = layoutUnit(this.print.sampleUnit(true), ctx);
    await this.audit.record({
      action: AuditAction.PRINT_DESIGN_TEST_PRINT,
      entityType: 'print_design',
      entityId: d.id,
      adminId: admin.id,
      ipHash: meta.ipHash,
      metadata: { designVersion: d.version, designSha256: d.sha256 },
    });
    const pdf = new SheetPdf({
      layout,
      fonts: this.print.fonts,
      title: `TEST PRINT — ${d.name} v${d.version}`,
    });
    res.status(200);
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader(
      'Content-Disposition',
      `attachment; filename="TEST-PRINT-design-v${d.version}-${layout.sheetWidthIn}x${layout.sheetHeightIn}.pdf"`,
    );
    res.setHeader('Cache-Control', 'no-store');
    pdf.doc.pipe(res);
    for (let i = 0; i < unitsPerSheet(layout); i++) pdf.addUnit(i, unit);
    pdf.end();
  }

  // ── Internals ───────────────────────────────────────────────────────────────────────────────

  private async insertVersion(
    v: {
      familyId: string;
      version: number;
      name: string;
      baseArtworkFileId: string;
      coverArtworkFileId: string | null;
      position: ArtworkPosition;
    },
    admin: AuthenticatedAdmin,
    tx: PrismaTx = this.prisma,
  ): Promise<DesignRow> {
    const name = v.name?.trim();
    if (!name) throw this.invalidArtwork('Design name is required.');
    const base = await this.fileRow(v.baseArtworkFileId, tx);
    const cover = v.coverArtworkFileId ? await this.fileRow(v.coverArtworkFileId, tx) : null;
    const check = this.check(base, cover, v.position);
    return tx.printDesign.create({
      data: {
        id: uuidv7(),
        familyId: v.familyId,
        version: v.version,
        name,
        status: 'DRAFT',
        artworkType: base.format,
        baseArtworkFileId: base.id,
        coverArtworkFileId: cover?.id ?? null,
        ...v.position,
        validationErrors: check.errors,
        validationWarnings: check.warnings,
        createdByAdminId: admin.id,
      },
      include,
    });
  }

  private check(base: FileRow, cover: FileRow | null, position: ArtworkPosition) {
    return checkDesign(
      this.facts(base),
      cover ? this.facts(cover) : null,
      position,
      this.print.geometry(DEFAULT_PRINT_LAYOUT).coverYellow,
    );
  }

  /**
   * Activation / production gate: static rules + files present with matching hash + the QR
   * geometry valid + a real sample PDF renders. Stores the result on the design.
   */
  private async fullValidation(row: DesignRow): Promise<string[]> {
    const position = {
      scalePercent: row.scalePercent,
      offsetXMm: row.offsetXMm,
      offsetYMm: row.offsetYMm,
    };
    const check = this.check(row.baseArtwork, row.coverArtwork, position);
    const errors = [...check.errors];
    const warnings = [...check.warnings];
    if (!errors.length) {
      try {
        const d = await this.loadRenderable(row.id);
        const ctx = this.print.context(DEFAULT_PRINT_LAYOUT, this.contextOptions(d));
        const issues = geometryIssues(ctx.geometry);
        if (issues.length) errors.push(...issues);
        await renderSamplePdf(ctx, this.print);
        for (const key of [d.base.key, d.cover?.key].filter(Boolean) as string[])
          for (const w of (lastSvgWarnings.get(key) ?? []).slice(0, 5))
            warnings.push(`Renderer: ${w}`);
      } catch (err) {
        errors.push(
          err instanceof AppException
            ? err.message
            : `Sample render failed: ${(err as Error).message}`,
        );
      }
    }
    await this.prisma.printDesign.update({
      where: { id: row.id },
      data: { validationErrors: errors, validationWarnings: [...new Set(warnings)] },
    });
    return errors;
  }

  private async loadAsset(f: FileRow): Promise<ArtworkAsset> {
    let file;
    try {
      file = await this.storage.get(f.storageKey);
    } catch {
      file = null;
    }
    if (!file || sha256(file.buffer) !== f.sha256) {
      this.logger.error(`Print artwork ${f.id} missing or altered (expected sha256 ${f.sha256})`);
      throw this.unavailable();
    }
    if (f.format === 'SVG') {
      const [x, y, width, height] = (f.svgViewBox ?? '').split(' ').map(Number);
      return {
        key: f.sha256,
        format: 'SVG',
        svg: file.buffer.toString('utf8'),
        viewBox: { x: x!, y: y!, width: width!, height: height! },
      };
    }
    return {
      key: f.sha256,
      format: 'PNG',
      png: file.buffer,
      widthPx: f.widthPx!,
      heightPx: f.heightPx!,
    };
  }

  private facts(f: FileRow): ArtworkFacts {
    const vb = f.svgViewBox?.split(' ').map(Number);
    return {
      format: f.format,
      widthPx: f.widthPx,
      heightPx: f.heightPx,
      viewBox: vb ? { width: vb[2]!, height: vb[3]! } : null,
      testOnly: f.testOnly,
      warnings: (f.warnings as string[] | null) ?? [],
    };
  }

  private position(p: Partial<ArtworkPosition>): ArtworkPosition {
    return {
      scalePercent: p.scalePercent ?? 100,
      offsetXMm: p.offsetXMm ?? 0,
      offsetYMm: p.offsetYMm ?? 0,
    };
  }

  private async findRow(id: string): Promise<DesignRow> {
    const row = await this.prisma.printDesign.findUnique({ where: { id }, include });
    if (!row)
      throw AppException.notFound(ErrorCode.PRINT_DESIGN_NOT_FOUND, 'Print design not found.');
    return row;
  }

  private async fileRow(id: string, tx: PrismaTx = this.prisma): Promise<FileRow> {
    const row = await tx.printArtworkFile.findUnique({ where: { id } });
    if (!row) throw this.invalidArtwork('Artwork file not found. Upload it again.');
    return row;
  }

  private async usage(ids: string[]): Promise<Map<string, number>> {
    if (!ids.length) return new Map();
    const rows = await this.prisma.safetyIdBatch.groupBy({
      by: ['printDesignId'],
      where: { printDesignId: { in: ids } },
      _count: { _all: true },
    });
    return new Map(rows.map((r) => [r.printDesignId!, r._count._all]));
  }

  fileDto(f: FileRow): PrintArtworkFileDto {
    return {
      id: f.id,
      format: f.format,
      originalFilename: f.originalFilename,
      mimeType: f.mimeType,
      sha256: f.sha256,
      sizeBytes: f.sizeBytes,
      widthPx: f.widthPx,
      heightPx: f.heightPx,
      svgViewBox: f.svgViewBox,
      effectiveDpi: f.effectiveDpi,
      quality: artworkQuality(f.format, f.effectiveDpi),
      testOnly: f.testOnly,
      warnings: (f.warnings as string[] | null) ?? [],
      createdAt: f.createdAt.toISOString(),
    };
  }

  private toDto(r: DesignRow, usedByBatches: number): PrintDesignDto {
    const position = {
      scalePercent: r.scalePercent,
      offsetXMm: r.offsetXMm,
      offsetYMm: r.offsetYMm,
    };
    const facts = this.facts(r.baseArtwork);
    const box = placeBaseArtwork(
      artworkAspect({
        format: facts.format,
        viewBox: facts.viewBox ? { x: 0, y: 0, ...facts.viewBox } : undefined,
        widthPx: facts.widthPx ?? undefined,
        heightPx: facts.heightPx ?? undefined,
      }),
      position,
    );
    const dpi =
      r.baseArtwork.format === 'PNG'
        ? drawnDpi(r.baseArtwork.widthPx!, r.baseArtwork.heightPx!, box)
        : null;
    const mmOf = (pt: number) => Math.round((pt * 25.4 * 100) / 72) / 100;
    return {
      id: r.id,
      familyId: r.familyId,
      name: r.name,
      version: r.version,
      status: r.status,
      artworkType: r.artworkType,
      baseArtwork: this.fileDto(r.baseArtwork),
      coverArtwork: r.coverArtwork ? this.fileDto(r.coverArtwork) : null,
      ...position,
      effectiveDpi: dpi,
      quality: artworkQuality(r.baseArtwork.format, dpi),
      artworkSizeMm: { width: mmOf(box.w), height: mmOf(box.h) },
      validationErrors: (r.validationErrors as string[] | null) ?? [],
      validationWarnings: (r.validationWarnings as string[] | null) ?? [],
      locked: r.status !== 'DRAFT' || usedByBatches > 0,
      usedByBatches,
      createdBy: r.creator,
      createdAt: r.createdAt.toISOString(),
      updatedAt: r.updatedAt.toISOString(),
      activatedAt: r.activatedAt?.toISOString() ?? null,
      archivedAt: r.archivedAt?.toISOString() ?? null,
    };
  }

  private async auditDesign(
    action: AuditAction,
    row: DesignRow,
    admin: AuthenticatedAdmin,
    meta: RequestMeta,
    extra: Record<string, unknown> = {},
  ): Promise<void> {
    await this.audit.record({
      action,
      entityType: 'print_design',
      entityId: row.id,
      adminId: admin.id,
      ipHash: meta.ipHash,
      metadata: {
        name: row.name,
        designVersion: row.version,
        familyId: row.familyId,
        designSha256: { base: row.baseArtwork.sha256, cover: row.coverArtwork?.sha256 ?? null },
        ...extra,
      },
    });
  }

  private invalidArtwork(message: string): AppException {
    return new AppException(ErrorCode.INVALID_ARTWORK, message, HttpStatus.BAD_REQUEST);
  }

  unavailable(): AppException {
    return new AppException(
      ErrorCode.PRINT_DESIGN_UNAVAILABLE,
      'The print design used by this batch is unavailable.',
      HttpStatus.CONFLICT,
    );
  }
}

